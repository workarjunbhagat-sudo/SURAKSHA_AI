def _normalize(text: str) -> str:
    return re.sub(r"\s+", " ", text.lower()).strip()

def rule_analysis(text: str) -> List[Dict]:
    t = _normalize(text)
    found = []
    for name, patterns in INDICATORS:
        if any(re.search(p, t) for p in patterns):
            found.append({"name": name, "explanation": EXPLANATIONS[name]})
    return found

def ml_probability(text: str) -> float:
    return float(ML_PIPELINE.predict_proba([_normalize(text)])[0][1])

def ml_label(text: str) -> str:
    return "Suspicious" if ML_PIPELINE.predict([_normalize(text)])[0] == 1 else "Lower risk"

def category(text: str) -> str:
    t = _normalize(text)
    if any(x in t for x in ["kyc", "bank account", "account will be blocked", "account will be suspended"]):
        return "Bank / KYC scam"
    if any(x in t for x in ["digital arrest", "arrest warrant", "police", "cyber crime"]):
        return "Authority / digital-arrest scam"
    if any(x in t for x in ["otp", "upi", "cvv", "customer care", "refund"]):
        return "Payment / UPI scam"
    if any(x in t for x in ["lottery", "prize", "reward", "cashback"]):
        return "Prize / reward scam"
    if any(x in t for x in ["job", "work from home", "registration fee"]):
        return "Job / recruitment scam"
    if any(x in t for x in ["investment", "guaranteed returns"]):
        return "Investment scam"
    if any(x in t for x in ["parcel", "customs fee"]):
        return "Delivery / parcel scam"
    return "Suspicious message"

